// Generates src/types.ts and src/resources.ts from spec/openapi.json and spec/methods.json.
// Run with `npm run generate` after updating the spec (curl -o spec/openapi.json https://api.satelit.md/openapi.json).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'spec/openapi.json'), 'utf8'));
const map = JSON.parse(readFileSync(join(root, 'spec/methods.json'), 'utf8'));
const overrides = JSON.parse(readFileSync(join(root, 'spec/overrides.json'), 'utf8'));
Object.assign(spec.components.schemas, overrides.schemas);
const schemas = spec.components.schemas;

const HEADER = '// Generated by scripts/generate.mjs from spec/openapi.json. Do not edit by hand.\n';
const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const pascal = (s) => s.replace(/(^|[._-])(\w)/g, (_, __, c) => c.toUpperCase());
const refName = (ref) => ref.split('/').pop();

// JSON Schema -> TypeScript type expression.
function ts(s, ind = '') {
  if (!s || typeof s !== 'object') return 'unknown';
  if (s.$ref) return refName(s.$ref);
  if (s.allOf) return s.allOf.map((x) => wrap(ts(x, ind))).join(' & ');
  if (s.oneOf || s.anyOf) return [...new Set((s.oneOf || s.anyOf).map((x) => ts(x, ind)))].join(' | ');
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (s.enum) {
    const lits = s.enum.map((v) => JSON.stringify(v));
    if (types.includes('null') && !s.enum.includes(null)) lits.push('null');
    return [...new Set(lits)].join(' | ');
  }
  if (!types.length) return s.properties ? obj(s, ind) : 'unknown';
  return [...new Set(types.map((t) => one(t, s, ind)))].join(' | ');
}
function wrap(t) {
  return /[|&]/.test(t) ? `(${t})` : t;
}
function one(t, s, ind) {
  switch (t) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${wrap(ts(s.items, ind))}[]`;
    case 'object': return obj(s, ind);
    default: return 'unknown';
  }
}
function obj(s, ind) {
  const props = s.properties || {};
  const keys = Object.keys(props);
  const extra = s.additionalProperties;
  if (!keys.length) {
    if (extra && typeof extra === 'object' && Object.keys(extra).length) return `Record<string, ${ts(extra, ind)}>`;
    return 'Record<string, unknown>';
  }
  const req = new Set(s.required || []);
  const inner = ind + '  ';
  const lines = keys.map((k) => `${inner}${ident(k)}${req.has(k) ? '' : '?'}: ${ts(props[k], inner)};`);
  return `{\n${lines.join('\n')}\n${ind}}`;
}

// The sentence that says what a call costs, from the route's description.
export function credits(op) {
  if (op.security && op.security.length === 0) return 'No key, 0 credits';
  const desc = op.description || '';
  const m = /(?:^|\s)costs? ([^.]*)\./i.exec(desc);
  let c = m ? `Costs ${m[1]}` : '';
  const plan = /^(Business and Enterprise|Enterprise)\./.exec(desc);
  if (plan) c = `${plan[1]} plans only. ${c}`;
  return c;
}

function dataType(op, nameHint, extraTypes) {
  const sch = op.responses?.['200']?.content?.['application/json']?.schema;
  const d = sch?.properties?.data;
  if (!d) return 'unknown';
  const t = ts(d);
  if (/^[\w]+(\[\])?$/.test(t) || /^\w+ \| null$/.test(t)) return t;
  extraTypes.push(`export type ${nameHint}Data = ${ts(d)};`);
  return `${nameHint}Data`;
}

// ---- types.ts
const typeLines = [HEADER];
for (const [name, s] of Object.entries(schemas)) {
  const t = ts(s);
  typeLines.push(t.startsWith('{') ? `export interface ${name} ${t}\n` : `export type ${name} = ${t};\n`);
}

// ---- resources.ts
const namespaces = {}; // 'news' -> {methods: [], children: Set}
const top = [];
const extraTypes = [];
const paramTypes = [];
for (const [path, full] of map.methods) {
  const op = spec.paths[path]?.get;
  if (!op) throw new Error(`no GET ${path} in spec`);
  const parts = full.split('.');
  const method = parts.pop();
  const ns = parts.join('.');
  const hint = pascal(ns ? `${ns}.${method}` : method);
  const params = (op.parameters || []).filter((p) => p.name !== 'lang');
  const pathParams = params.filter((p) => p.in === 'path');
  const query = params.filter((p) => p.in === 'query');
  let paramsType = null;
  if (query.length) {
    paramsType = `${hint}Params`;
    const lines = query.map((p) => {
      const doc = p.description ? `  /** ${p.description.replace(/\*\//g, '*\\/').split('\n')[0]} */\n` : '';
      let t = ts(p.schema);
      if (p.schema?.type === 'boolean') t = 'boolean';
      if (/types|seen|exclude_flags/.test(p.name) && t === 'string') t = 'string | string[]';
      return `${doc}  ${ident(p.name)}${p.required ? '' : '?'}: ${t};`;
    });
    paramTypes.push(`export interface ${paramsType} {\n${lines.join('\n')}\n}\n`);
  }
  const m = {
    path, method, ns, op, pathParams, paramsType,
    required: query.some((p) => p.required),
    data: dataType(op, hint, extraTypes),
  };
  if (!ns) top.push(m);
  else {
    (namespaces[ns] ||= { methods: [] }).methods.push(m);
  }
}

const typeRef = (t) => t.replace(/\b([A-Z]\w*)\b/g, 'T.$1');

function methodCode(m, recv) {
  const args = [];
  const doc = [`/** ${m.op.summary}.`, credits(m.op) ? ` ${credits(m.op)}.` : '', ` \`GET ${m.path}\` */`].join('');
  for (const p of m.pathParams) args.push(`${p.name}: ${p.schema?.type === 'integer' ? 'number | string' : 'string'}`);
  if (m.paramsType) args.push(`params${m.required ? '' : '?'}: ${m.paramsType}`);
  args.push('opts?: CallOptions');
  let pathExpr = '`' + m.path.replace(/\{(\w+)\}/g, (_, n) => '${seg(' + n + ')}') + '`';
  if (!m.pathParams.length) pathExpr = `'${m.path}'`;
  return `  ${doc}\n  readonly ${m.method} = (${args.join(', ')}): Promise<ApiResponse<${typeRef(m.data)}>> =>\n    ${recv}.get(${pathExpr}, ${m.paramsType ? 'params' : 'undefined'}, opts);`;
}

const helpers = { feed: 'FeedHelpers' };
const nsClasses = [];
const nsNames = Object.keys(namespaces);
for (const ns of nsNames) {
  const cls = `${pascal(ns)}Api`;
  const children = nsNames.filter((n) => n.startsWith(ns + '.') && n.split('.').length === ns.split('.').length + 1);
  const base = helpers[ns] ? ` extends ${helpers[ns]}` : '';
  const lines = [`/** ${map.namespaces[ns] || ns} */`, `export class ${cls}${base} {`];
  for (const c of children) lines.push(`  readonly ${c.split('.').pop()}: ${pascal(c)}Api;`);
  lines.push(`  constructor(private readonly c: Transport) {`);
  if (base) lines.push('    super();');
  for (const c of children) lines.push(`    this.${c.split('.').pop()} = new ${pascal(c)}Api(c);`);
  lines.push('  }');
  for (const m of namespaces[ns].methods) lines.push(methodCode(m, 'this.c'));
  lines.push('}\n');
  nsClasses.push(lines.join('\n'));
}

const res = [
  HEADER,
  "import { SatelitCore, seg } from './core.js';",
  "import type { ApiResponse, CallOptions, Transport } from './core.js';",
  "import { ExportApi } from './export.js';",
  "import { FeedHelpers } from './helpers.js';",
  "import type * as T from './types.js';\n",
  ...paramTypes,
  ...nsClasses,
  '/**',
  ' * The Satelit data API client.',
  ' *',
  ' * ```ts',
  " * const satelit = new Satelit({ apiKey: process.env.SATELIT_API_KEY });",
  ' * const { data, meta } = await satelit.rates.list();',
  ' * ```',
  ' */',
  'export class Satelit extends SatelitCore {',
  ...nsNames.filter((n) => !n.includes('.')).map((n) => `  readonly ${n} = new ${pascal(n)}Api(this);`),
  '  /** Whole products as NDJSON (Enterprise). `GET /export/{product}` */',
  '  readonly export = new ExportApi(this);',
  ...top.map((m) => methodCode(m, 'this')),
  '}\n',
].join('\n');

writeFileSync(join(root, 'src/types.ts'), typeLines.join('\n') + '\n' + extraTypes.join('\n\n') + '\n');
writeFileSync(join(root, 'src/resources.ts'), res);

// A machine-readable method list for the README table and the tests: [name, path, credits, signature].
const sig = (m) => {
  const a = m.pathParams.map((p) => p.name);
  if (m.paramsType) a.push(m.required ? '{ ' + m.op.parameters.filter((p) => p.required && p.in === 'query').map((p) => p.name).join(', ') + ', … }' : 'params?');
  return a.join(', ');
};
const table = [];
for (const ns of nsNames) for (const m of namespaces[ns].methods) table.push([`${ns}.${m.method}`, m.path, credits(m.op), sig(m)]);
for (const m of top) table.push([m.method, m.path, credits(m.op), sig(m)]);
writeFileSync(join(root, 'spec/method-table.json'), JSON.stringify(table, null, 1) + '\n');

// The README's method table, between its markers.
const readme = join(root, 'README.md');
try {
  const text = readFileSync(readme, 'utf8');
  const rows = table.map(([n, p, c, a]) => `| \`${n}(${a})\` | \`${p}\` | ${c.replace(/\|/g, '/')} |`);
  const block = ['<!-- methods:start -->', '| Method | Route | Credits |', '|---|---|---|', ...rows, '<!-- methods:end -->'].join('\n');
  writeFileSync(readme, text.replace(/<!-- methods:start -->[\s\S]*<!-- methods:end -->/, block));
} catch {
  // no README yet
}
console.log(`types: ${Object.keys(schemas).length}, methods: ${table.length}`);
